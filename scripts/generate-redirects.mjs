/**
 * Generates public/_redirects for Netlify from scraped WP URLs → new app routes.
 * Run: node scripts/generate-redirects.mjs
 * Also invoked from the production build.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

function readJson(path) {
  const raw = readFileSync(path, 'utf8').replace(/^\uFEFF/, '')
  return JSON.parse(raw)
}

const scraped = readJson(resolve('scripts/scraped-listings.json'))
const imported = readJson(resolve('src/data/importedListings.json'))

const byId = new Map(imported.map((p) => [p.id, p]))
const ids = [...byId.keys()]

function slugFromUrl(url) {
  const match = String(url).match(/\/property\/([^/?#]+)\/?$/)
  if (!match) return null
  try {
    return decodeURIComponent(match[1]).toLowerCase()
  } catch {
    return match[1].toLowerCase()
  }
}

function resolveListingId(slug, listingType) {
  if (!slug) return null

  const preferred =
    listingType === 'rental' ? [`r-${slug}`, slug] : [slug, `r-${slug}`]

  for (const candidate of preferred) {
    if (byId.has(candidate)) {
      const listing = byId.get(candidate)
      if (listingType === 'rental' && listing.listingType !== 'rental') continue
      if (listingType === 'sale' && listing.listingType !== 'sale') continue
      return candidate
    }
  }

  return (
    ids.find((id) => {
      const bare = id.startsWith('r-') ? id.slice(2) : id
      const isRentalId = id.startsWith('r-')
      if (listingType === 'rental' && !isRentalId) return false
      if (listingType === 'sale' && isRentalId) return false
      return slug === bare || slug.startsWith(bare)
    }) ?? null
  )
}

function addRedirect(map, from, to) {
  const normalizedFrom = from.startsWith('/') ? from : `/${from}`
  if (!map.has(normalizedFrom)) map.set(normalizedFrom, to)
}

const redirects = new Map()

// Legacy WordPress section / marketing paths → closest new routes
const staticRedirects = [
  ['/property-status/for-sale', '/sales'],
  ['/property-status/for-sale/', '/sales'],
  ['/property-status/for-rent', '/rentals'],
  ['/property-status/for-rent/', '/rentals'],
  ['/properties/', '/properties'],
  ['/property/', '/properties'],
  ['/about-us', '/about'],
  ['/about-us/', '/about'],
  ['/about-us.html', '/about'],
  ['/contact-us', '/contact'],
  ['/contact-us/', '/contact'],
  ['/contact-us.html', '/contact'],
  ['/blog', '/magazine'],
  ['/blog/', '/magazine'],
  ['/category/blog', '/magazine'],
  ['/category/blog/', '/magazine'],
  ['/sellers-package/', '/sellers-package'],
  ['/services/', '/services'],
  ['/home', '/'],
  ['/home/', '/'],
  ['/index.php', '/'],
]

for (const [from, to] of staticRedirects) addRedirect(redirects, from, to)

// Paginated archives
addRedirect(redirects, '/property-status/for-sale/*', '/sales')
addRedirect(redirects, '/property-status/for-rent/*', '/rentals')

let mapped = 0
let fallback = 0

for (const item of scraped.sales ?? []) {
  const slug = slugFromUrl(item.url)
  if (!slug) continue
  const id = resolveListingId(slug, 'sale')
  const to = id ? `/property/sale/${id}` : '/sales'
  if (id) mapped += 1
  else fallback += 1
  addRedirect(redirects, `/property/${slug}`, to)
  addRedirect(redirects, `/property/${slug}/`, to)
}

for (const item of scraped.rentals ?? []) {
  const slug = slugFromUrl(item.url)
  if (!slug) continue
  const id = resolveListingId(slug, 'rental')
  const to = id ? `/property/rental/${id}` : '/rentals'
  if (id) mapped += 1
  else fallback += 1
  addRedirect(redirects, `/property/${slug}`, to)
  addRedirect(redirects, `/property/${slug}/`, to)
}

// Encoded emoji slug variant from WP
addRedirect(
  redirects,
  '/property/%e2%9c%a8-for-rent-beautifully-designed-apartment-in-a-conservation-building-in-the-heart-of-tel-aviv-%e2%9c%a8',
  '/rentals',
)
addRedirect(
  redirects,
  '/property/%e2%9c%a8-for-rent-beautifully-designed-apartment-in-a-conservation-building-in-the-heart-of-tel-aviv-%e2%9c%a8/',
  '/rentals',
)

  const lines = [
  '# Generated by scripts/generate-redirects.mjs - do not edit by hand.',
  '# Legacy WordPress -> new ProperTLV SPA routes (301).',
  '# Specific rules must stay above the SPA fallback.',
  '',
]

for (const [from, to] of redirects) {
  lines.push(`${from}  ${to}  301`)
}

lines.push('')
lines.push('# SPA fallback for client-side routes')
lines.push('/*  /index.html  200')
lines.push('')

const outputPath = resolve('public', '_redirects')
writeFileSync(outputPath, lines.join('\n'), 'utf8')

console.log(
  `Wrote ${redirects.size} redirect rules to ${outputPath} (listing matches: ${mapped}, section fallbacks: ${fallback})`,
)

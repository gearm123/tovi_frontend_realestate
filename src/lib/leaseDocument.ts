function tenantBlock(
  label: string,
  name: string,
  idNumber: string,
  address: string,
  phone: string,
  email: string,
): string {
  if (!name.trim() && !idNumber.trim()) return ''
  return [
    `שוכר ${label}: ${clean(name) || '____'}`,
    `ת״ז: ${clean(idNumber) || '____'}`,
    `כתובת: ${clean(address) || '____'}`,
    `טלפון: ${clean(phone) || '____'}`,
    `דוא״ל: ${clean(email) || '____'}`,
  ].join('\n')
}

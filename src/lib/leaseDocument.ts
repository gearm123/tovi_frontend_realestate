import type { LeaseDetails } from '../types/contract'

const MONTHS = [
  'ינואר',
  'פברואר',
  'מרץ',
  'אפריל',
  'מאי',
  'יוני',
  'יולי',
  'אוגוסט',
  'ספטמבר',
  'אוקטובר',
  'נובמבר',
  'דצמבר',
]

function clean(value: string): string {
  return value.replace(/\s+/g, ' ').trim()
}

export function displayDate(value: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value.trim())
  if (!match) return clean(value)
  return `${Number(match[3])}.${Number(match[2])}.${match[1]}`
}

function signedOn(details: LeaseDetails): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(details.signingDate.trim())
  const city = clean(details.signingCity) || 'תל אביב'
  if (!match) {
    const raw = clean(details.signingDate)
    return raw ? `שנערך ונחתם ב${city} ביום ${raw}` : `שנערך ונחתם ב${city}`
  }
  const month = MONTHS[Number(match[2]) - 1] ?? match[2]
  return `שנערך ונחתם ב${city} ביום ${Number(match[3])} לחודש ${month} שנת ${match[1]}`
}

function money(value: string): string {
  const amount = clean(value).replace(/,/g, '')
  if (!amount) return '₪____'
  const numeric = Number(amount)
  if (!Number.isFinite(numeric)) return `₪${amount}`
  return `₪${numeric.toLocaleString('en-US')}`
}

export function contractHeading(details: LeaseDetails): string {
  const street = clean(details.propertyStreet) || '____'
  const city = clean(details.propertyCity) || '____'
  return `דירת מגורים – ${street}, ${city}`
}

export function contractParties(details: LeaseDetails): string {
  const tenants = [clean(details.tenant1Name), clean(details.tenant2Name)].filter(Boolean)
  const street = clean(details.propertyStreet)
  return [tenants.join(' ו-'), street].filter(Boolean).join(' · ') || 'הסכם שכירות'
}

